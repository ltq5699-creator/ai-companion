// ============================================================================
// 时间感知：把"当前时间"转成人类可读标签 + 主动问候指令
// ============================================================================

export type TimeContext = {
  label: string; // 早晨 / 中午 / 傍晚 / 深夜 / 白天
  isGreeting: boolean; // 是否为固定时段的主动问候
  hour: number;
};

export function buildTimeContext(date = new Date()): TimeContext {
  const hour = date.getHours();
  let label = '白天';
  if (hour >= 5 && hour < 10) label = '早晨';
  else if (hour >= 10 && hour < 14) label = '中午';
  else if (hour >= 14 && hour < 19) label = '傍晚前';
  else if (hour >= 19 && hour < 23) label = '晚上';
  else label = '深夜';
  return { label, isGreeting: false, hour };
}

